    def plot_depth_by_ranges(self, df_comparison, n_ranges=6):
        """Análise de desempenho por faixas de profundidade"""
        if 'y_true' not in df_comparison.columns:
            print("Erro: Coluna 'y_true' não encontrada")
            return

        # Verificar modelos disponíveis
        model_cols = [col for col in df_comparison.columns if col.startswith('y_pred_')]
        model_names = [col.replace('y_pred_', '') for col in model_cols]

        if not model_names:
            print("Erro: Nenhum modelo encontrado")
            return

        print(f"Modelos encontrados: {model_names}")
        print(f"Número total de amostras: {len(df_comparison)}")

        # Criar faixas de profundidade baseadas nos quantis
        df_comparison = df_comparison.copy()
        df_comparison['depth_range'] = pd.qcut(
            df_comparison['y_true'],
            q=n_ranges,
            duplicates='drop',
            precision=2
        )

        # Ordenar faixas da mais profunda para a mais rasa (ou vice-versa conforme sua preferência)
        depth_ranges = sorted(df_comparison['depth_range'].dropna().unique())

        # Criar labels formatadas para as faixas
        range_labels = []
        for range_val in depth_ranges:
            # Verificar se é um intervalo válido
            if hasattr(range_val, 'left') and hasattr(range_val, 'right'):
                # Ordenar do mais profundo (negativo maior) para o mais raso
                left = min(range_val.left, range_val.right)
                right = max(range_val.left, range_val.right)
                label = f"{left:.2f} a {right:.2f}"
                range_labels.append(label)
            else:
                range_labels.append(str(range_val))

        # Dicionário para armazenar métricas por faixa
        metrics_by_range = {model: {'rmse': [], 'r2': [], 'bias': [], 'n_samples': []}
                          for model in model_names}

        # Calcular métricas para cada faixa e modelo
        for range_val in depth_ranges:
            mask = df_comparison['depth_range'] == range_val
            n_samples = mask.sum()

            if n_samples < 5:  # Mínimo de amostras para cálculo confiável
                print(f"Aviso: Faixa {range_val} tem apenas {n_samples} amostras")
                for model in model_names:
                    metrics_by_range[model]['rmse'].append(np.nan)
                    metrics_by_range[model]['r2'].append(np.nan)
                    metrics_by_range[model]['bias'].append(np.nan)
                    metrics_by_range[model]['n_samples'].append(n_samples)
                continue

            print(f"\nFaixa: {range_val} - {n_samples} amostras")

            for model in model_names:
                pred_col = f'y_pred_{model}'

                if pred_col not in df_comparison.columns:
                    metrics_by_range[model]['rmse'].append(np.nan)
                    metrics_by_range[model]['r2'].append(np.nan)
                    metrics_by_range[model]['bias'].append(np.nan)
                    metrics_by_range[model]['n_samples'].append(np.nan)
                    continue

                # Filtrar dados da faixa atual
                y_true_range = df_comparison.loc[mask, 'y_true'].values
                y_pred_range = df_comparison.loc[mask, pred_col].values

                # Verificar se há dados válidos
                valid_mask = ~np.isnan(y_true_range) & ~np.isnan(y_pred_range)
                y_true_valid = y_true_range[valid_mask]
                y_pred_valid = y_pred_range[valid_mask]

                n_valid = len(y_true_valid)

                if n_valid < 3:
                    print(f"  {model}: Apenas {n_valid} amostras válidas")
                    metrics_by_range[model]['rmse'].append(np.nan)
                    metrics_by_range[model]['r2'].append(np.nan)
                    metrics_by_range[model]['bias'].append(np.nan)
                    metrics_by_range[model]['n_samples'].append(n_valid)
                    continue

                # Calcular métricas
                try:
                    # RMSE
                    rmse = np.sqrt(mean_squared_error(y_true_valid, y_pred_valid))

                    # R² - com proteção contra valores extremos
                    if len(np.unique(y_true_valid)) > 1:
                        r2 = r2_score(y_true_valid, y_pred_valid)
                        # Limitar R² entre -1 e 1
                        r2 = np.clip(r2, -1, 1)
                    else:
                        r2 = np.nan

                    # Bias
                    bias = np.mean(y_pred_valid - y_true_valid)

                    # Armazenar métricas
                    metrics_by_range[model]['rmse'].append(rmse)
                    metrics_by_range[model]['r2'].append(r2)
                    metrics_by_range[model]['bias'].append(bias)
                    metrics_by_range[model]['n_samples'].append(n_valid)

                    print(f"  {model}: RMSE={rmse:.3f}, R²={r2:.3f}, Bias={bias:.3f}")

                except Exception as e:
                    print(f"  {model}: Erro no cálculo - {str(e)}")
                    metrics_by_range[model]['rmse'].append(np.nan)
                    metrics_by_range[model]['r2'].append(np.nan)
                    metrics_by_range[model]['bias'].append(np.nan)
                    metrics_by_range[model]['n_samples'].append(n_valid)

        # Criar gráficos
        fig, axes = plt.subplots(2, 2, figsize=(16, 12))
        axes = axes.flatten()

