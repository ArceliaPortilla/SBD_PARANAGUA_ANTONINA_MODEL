            x_extent_km = (x_max - x_min) * 111
            y_extent_km = (y_max - y_min) * 111
            print(f"Extensión: {x_extent_km:.1f} km (E-O) × {y_extent_km:.1f} km (N-S)")

            # Perfil 1: Horizontal (Este-Oeste)
            if x_extent_km > 0.5:  # Solo si hay suficiente extensión (>0.5 km)
                start_ew = (x_min + (x_max - x_min) * 0.2, y_center)
                end_ew = (x_max - (x_max - x_min) * 0.2, y_center)

