def processar():
    print("Carregando dados TPXO...")
    h_tpxo = xr.open_dataset(arquivo_h)

    # Preparar interpoladores
    lon_1d, lat_1d, interp_ha, interp_hp, omega_rad = preparar_interpoladores(h_tpxo)
    print(f"Grade TPXO: {len(lon_1d)} longitudes × {len(lat_1d)} latitudes")
    print(f"Intervalo de longitudes: {lon_1d.min():.2f}° a {lon_1d.max():.2f}°")
    print(f"Intervalo de latitudes:  {lat_1d.min():.2f}° a {lat_1d.max():.2f}°")

    arquivos = glob.glob(os.path.join(pasta_csv, "*.csv"))
    if not arquivos:
        print("Nenhum arquivo CSV encontrado.")
        return

    print(f"Encontrados {len(arquivos)} arquivos.\n")
    resumo = []

    for arq in arquivos:
        nome = os.path.basename(arq)
        print(f"Processando: {nome}")

        try:
            # Leitura do CSV
            try:
                df = pd.read_csv(arq, encoding='utf-8')
            except UnicodeDecodeError:
                df = pd.read_csv(arq, encoding='latin1')

            # Identificar colunas
            col_lat, col_lon, col_z, col_dt = identificar_colunas(df)

            # Renomear para nomes padrão
            mapping = {col_lat: 'lat', col_lon: 'lon', col_z: 'z', col_dt: 'datetime'}
            df = renomear_seguro(df, mapping)

            # Converter datetime
            df['datetime'] = pd.to_datetime(df['datetime'], errors='coerce')
            if df['datetime'].isna().any():
                data_hora = df['datetime'].dropna().iloc[0]
            else:
                data_hora = df['datetime'].iloc[0]

            # Horas desde época (1992-01-01)
            horas = horas_desde_epoca(data_hora)

            # Calcular maré para cada ponto
            eta = calcular_mare(df['lon'].values, df['lat'].values, horas,
                                lon_1d, lat_1d, interp_ha, interp_hp, omega_rad)

            # Delta espacial (IDW)
            delta = delta_idw(df['lon'].values, df['lat'].values)

            # Correção
            df['eta_MSL'] = eta
            df['Delta'] = delta
            df['Z_corrigido'] = df['z'] - (eta - delta)
            df['dif'] = df['Z_corrigido'] - df['z']

            # Salvar
            out_file = os.path.join(pasta_saida, nome.replace('.csv', '_corrigido.csv'))
            df.to_csv(out_file, index=False)

            # Resumo
            resumo.append({
                'Arquivo': nome,
                'Data_Hora': data_hora,
                'Eta_medio': np.nanmean(eta),
                'Delta_medio': np.nanmean(delta),
                'Correcao_media': np.nanmean(df['dif']),
                'Prof_orig_media': np.nanmean(df['z']),
                'Prof_corr_media': np.nanmean(df['Z_corrigido']),
                'Num_pontos': len(df)
            })

            print(f"  -> Correção média: {np.nanmean(df['dif']):+.3f} m")
            print(f"  -> η_MSL médio   : {np.nanmean(eta):+.3f} m")

        except Exception as e:
            print(f"  ERRO: {e}")
            if 'df' in locals():
                print("  Colunas:", list(df.columns))
            continue

    h_tpxo.close()

    if resumo:
        df_resumo = pd.DataFrame(resumo)
        df_resumo.to_csv(os.path.join(pasta_saida, 'resumo_correcoes.csv'), index=False)
        print("\nResumo salvo em:", os.path.join(pasta_saida, 'resumo_correcoes.csv'))
        return df_resumo
    else:
        print("Nenhum arquivo foi processado.")
        return None

