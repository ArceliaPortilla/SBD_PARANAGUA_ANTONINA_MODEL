    def _convertir_a_serializable(self, obj):
        """
        Convierte objetos numpy a tipos serializables para JSON
        """
        if isinstance(obj, dict):
            return {k: self._convertir_a_serializable(v) for k, v in obj.items()}
        elif isinstance(obj, (list, tuple)):
            return [self._convertir_a_serializable(item) for item in obj]
        elif isinstance(obj, np.integer):
            return int(obj)
        elif isinstance(obj, np.floating):
            return float(obj)
        elif isinstance(obj, np.ndarray):
            return obj.tolist()
        elif hasattr(obj, 'pattern') or isinstance(obj, re.Pattern):
            return str(obj.pattern) if hasattr(obj, 'pattern') else str(obj)
        elif isinstance(obj, pd.DataFrame):
            return obj.to_dict(orient='records')
        elif isinstance(obj, pd.Series):
            return obj.to_dict()
        else:
            return obj

