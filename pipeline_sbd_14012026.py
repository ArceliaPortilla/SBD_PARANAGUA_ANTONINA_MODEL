        if missing_cols:
            print(f" Columnas faltantes para crear perfil: {missing_cols}")
            print(f"   Columnas disponibles: {list(df.columns)}")
            return None

        # Generar puntos a lo largo de la línea
        x_line = np.linspace(start_point[0], end_point[0], num_points)
        y_line = np.linspace(start_point[1], end_point[1], num_points)

        # Calcular distancias acumuladas (en grados)
        distances = np.sqrt((x_line - x_line[0])**2 + (y_line - y_line[0])**2)

        # Interpolar valores en los puntos de la línea
        from scipy.interpolate import griddata
        from scipy.spatial import cKDTree

        # Preparar datos de entrada - ELIMINAR DUPLICADOS
        points = df[['X', 'Y']].values
        values_real = df[depth_col].values

        # Eliminar NaN
        mask_real = ~np.isnan(values_real)
        if mask_real.sum() < 3:
            print(f" Insuficientes datos no-NaN: {mask_real.sum()}")
            return None

        points_real = points[mask_real]
        values_real_clean = values_real[mask_real]

        # Eliminar duplicados en coordenadas (causan problemas con Qhull)
        points_real_unique, indices_unique = np.unique(points_real, axis=0, return_index=True)
        values_real_unique = values_real_clean[indices_unique]

        if len(points_real_unique) < 3:
            print(f" Insuficientes puntos únicos: {len(points_real_unique)}")
            return None

        # Interpolar profundidad real con manejo de errores
        try:
            # Primero intentar con método 'linear' pero con QJ para evitar problemas
            z_real_interp = griddata(points_real_unique, values_real_unique,
                                   (x_line, y_line), method='linear', fill_value=np.nan)

            # Si hay muchos NaN, intentar con 'nearest'
            nan_count = np.isnan(z_real_interp).sum()
            if nan_count > num_points * 0.3:  # Más del 30% NaN
                print(f" Muchos NaN con interpolación lineal ({nan_count}/{num_points}), probando 'nearest'")
                z_real_interp = griddata(points_real_unique, values_real_unique,
                                       (x_line, y_line), method='nearest', fill_value=np.nan)

        except Exception as e:
            print(f" Error en interpolación: {e}")
            print(" Usando método de vecino más cercano...")
            # Usar método más simple si falla
            tree = cKDTree(points_real_unique)
            distances_kd, indices = tree.query(np.column_stack([x_line, y_line]), k=1)
            z_real_interp = values_real_unique[indices]

        # Crear DataFrame del perfil
        profile_df = pd.DataFrame({
            'distance_deg': distances,
            'x': x_line,
            'y': y_line,
            'z_real': z_real_interp
        })

        # Interpolar predicciones de modelos (si existen) - CORREGIDO
        model_cols = [col for col in df.columns if col.startswith('y_pred_')]

        for col in model_cols:
            try:
                model_name = col.replace('y_pred_', '')
                values_pred = df[col].values

                # Filtrar NaN y preparar puntos para este modelo específico
                mask_pred = ~np.isnan(values_pred)
                if mask_pred.sum() < 3:
                    print(f" Insuficientes datos para modelo {model_name}: {mask_pred.sum()}")
                    continue

                points_pred = points[mask_pred]
                values_pred_clean = values_pred[mask_pred]

                # Eliminar duplicados
                points_pred_unique, indices_pred = np.unique(points_pred, axis=0, return_index=True)
                values_pred_unique = values_pred_clean[indices_pred]

                if len(points_pred_unique) < 3:
                    print(f" Insuficientes puntos únicos para modelo {model_name}")
                    continue

                # Interpolar usando los mismos métodos
                try:
                    z_pred = griddata(points_pred_unique, values_pred_unique,
                                    (x_line, y_line), method='linear', fill_value=np.nan)

                    # Verificar calidad de interpolación
                    nan_count_pred = np.isnan(z_pred).sum()
                    if nan_count_pred > num_points * 0.5:
                        z_pred = griddata(points_pred_unique, values_pred_unique,
                                        (x_line, y_line), method='nearest', fill_value=np.nan)

                except Exception as e:
                    print(f" Error interpolando modelo {model_name}: {e}")
                    # Usar vecino más cercano
                    tree_pred = cKDTree(points_pred_unique)
                    _, indices_pred = tree_pred.query(np.column_stack([x_line, y_line]), k=1)
                    z_pred = values_pred_unique[indices_pred]

                profile_df[f'z_pred_{model_name}'] = z_pred
                print(f"   Modelo {model_name} interpolado correctamente")

            except Exception as e:
                print(f" No se pudo interpolar modelo {col}: {e}")

        # Calcular errores si hay predicciones
        for model_name in [col.replace('z_pred_', '') for col in profile_df.columns if col.startswith('z_pred_')]:
            pred_col = f'z_pred_{model_name}'
            if pred_col in profile_df.columns:
                profile_df[f'error_{model_name}'] = profile_df[pred_col] - profile_df['z_real']
                profile_df[f'abs_error_{model_name}'] = np.abs(profile_df[f'error_{model_name}'])

        # Convertir distancia a metros (aproximación: 1° ≈ 111,000 m)
        profile_df['distance_m'] = profile_df['distance_deg'] * 111000

        # Guardar información del perfil
        profile_info = {
            'start_point': tuple(start_point) if not isinstance(start_point, tuple) else start_point,
            'end_point': tuple(end_point) if not isinstance(end_point, tuple) else end_point,
            'num_points': num_points,
            'length_deg': float(distances[-1]),
            'length_m': float(distances[-1] * 111000),
            'depth_column': depth_col,
            'df': profile_df
        }

        return profile_info

