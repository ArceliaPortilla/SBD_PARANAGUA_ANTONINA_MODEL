    def plot_statistical_comparison(self, df_comparison):
        """
        Comparação estatística detalhada entre modelos
        """
        model_cols = [col for col in df_comparison.columns if col.startswith('y_pred_')]
        model_names = [col.replace('y_pred_', '') for col in model_cols]

        if len(model_names) < 2:
            return

        # Calcular métricas para cada modelo
        metrics_data = []

        for model_name in model_names:
            pred_col = f'y_pred_{model_name}'
            if pred_col not in df_comparison.columns:
                continue

            mask = ~df_comparison['y_true'].isna() & ~df_comparison[pred_col].isna()
            y_true = df_comparison.loc[mask, 'y_true']
            y_pred = df_comparison.loc[mask, pred_col]

            if len(y_true) < 10:
                continue

            metrics = {
                'Modelo': model_name,
                'RMSE': np.sqrt(mean_squared_error(y_true, y_pred)),
                'MAE': mean_absolute_error(y_true, y_pred),
                'R²': r2_score(y_true, y_pred),
                'Bias': np.mean(y_pred - y_true),
                'Std_Error': np.std(y_pred - y_true),
                'N': len(y_true)
            }
            metrics_data.append(metrics)

        if not metrics_data:
            return

        df_metrics = pd.DataFrame(metrics_data)
        df_metrics = df_metrics.set_index('Modelo')

        # Gráfico de comparação
        metrics_to_plot = ['RMSE', 'MAE', 'R²']

        fig, axes = plt.subplots(1, 3, figsize=(15, 5))

        for idx, metric in enumerate(metrics_to_plot):
            if metric not in df_metrics.columns:
                continue

            values = df_metrics[metric].values
            models = df_metrics.index

            # Ordenar para melhor visualização
            if metric == 'R²':
                # Para R², maior é melhor
                sorted_idx = np.argsort(values)[::-1]
            else:
                # Para RMSE e MAE, menor é melhor
                sorted_idx = np.argsort(values)

            values = values[sorted_idx]
            models = models[sorted_idx]

            # Cores
            colors = [self.model_colors.get(model, plt.cm.tab10_r(i/len(models)))
                     for i, model in enumerate(models)]

            bars = axes[idx].bar(models, values, color=colors)
