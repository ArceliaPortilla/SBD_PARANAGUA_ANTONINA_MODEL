class SDBModeler:
    """Modelado de Batimetría por Satélite"""

    def __init__(self, config):
        self.config = config
        self.models = {}
        self.results = {}
        self.predictions = {}

    @staticmethod
    def calculate_metrics(y_true, y_pred):
        """Calcula métricas de evaluación"""
        return {
            'RMSE': np.sqrt(mean_squared_error(y_true, y_pred)),
            'MAE': mean_absolute_error(y_true, y_pred),
            'R2': r2_score(y_true, y_pred),
            'Bias': np.mean(y_pred - y_true),
            'Std_Error': np.std(y_pred - y_true)
        }

    def train_all_models(self, splits):
        """Entrena todos los modelos disponibles"""
        print("\n" + "=" * 80)
        print("ENTRENANDO MODELOS")
        print("=" * 80)

        # 1. Lyzenga (Regresión lineal multivariada)
        if 'X_lyz_train' in splits and splits['X_lyz_train'].shape[0] > 10:
            print("\n1. Entrenando modelo Lyzenga...")
            lyz_model = LinearRegression()
            lyz_model.fit(splits['X_lyz_train'], splits['y_train'])

            y_pred = lyz_model.predict(splits['X_lyz_test'])
            self.models['Lyzenga'] = lyz_model
            self.results['Lyzenga'] = self.calculate_metrics(splits['y_test'], y_pred)
            self.predictions['Lyzenga'] = y_pred

            print(f"   Coeficientes: {lyz_model.coef_}")
            print(f"   Intercepto: {lyz_model.intercept_:.3f}")

        # 2. Stumpf (Regresión lineal simple)
        if 'X_stumpf_train' in splits and splits['X_stumpf_train'].shape[0] > 10:
            print("\n2. Entrenando modelo Stumpf...")
            stumpf_model = LinearRegression()
            stumpf_model.fit(splits['X_stumpf_train'], splits['y_train'])

            y_pred = stumpf_model.predict(splits['X_stumpf_test'])
            self.models['Stumpf'] = stumpf_model
            self.results['Stumpf'] = self.calculate_metrics(splits['y_test'], y_pred)
            self.predictions['Stumpf'] = y_pred

            print(f"   Coeficiente: {stumpf_model.coef_[0]:.3f}")
            print(f"   Intercepto: {stumpf_model.intercept_:.3f}")

        # 3. Modelos de Machine Learning
        if 'X_ml_train_scaled' in splits:
            min_samples = self.config.get('min_train_samples', 30)

            if splits['X_ml_train_scaled'].shape[0] < min_samples:
                print(f"\n Insuficientes datos para ML: {splits['X_ml_train_scaled'].shape[0]} < {min_samples}")
            else:
                print("\n3. Entrenando modelos de Machine Learning...")

                # Random Forest
                print("  a) Random Forest...")
                rf_model = RandomForestRegressor(
                    n_estimators=self.config.get('rf_n_estimators', 200),
                    max_depth=self.config.get('rf_max_depth', 12),
                    random_state=self.config.get('random_state', 42),
                    n_jobs=-1
                )
                rf_model.fit(splits['X_ml_train_scaled'], splits['y_train'])
                y_pred = rf_model.predict(splits['X_ml_test_scaled'])
                self.models['RF'] = rf_model
                self.results['RF'] = self.calculate_metrics(splits['y_test'], y_pred)
                self.predictions['RF'] = y_pred

                # XGBoost
                print("  b) XGBoost...")
                xgb_model = xgb.XGBRegressor(
                    n_estimators=self.config.get('xgb_n_estimators', 200),
                    max_depth=self.config.get('xgb_max_depth', 6),
                    learning_rate=self.config.get('xgb_learning_rate', 0.05),
                    random_state=self.config.get('random_state', 42),
                    n_jobs=4
                )
                xgb_model.fit(splits['X_ml_train_scaled'], splits['y_train'])
                y_pred = xgb_model.predict(splits['X_ml_test_scaled'])
                self.models['XGB'] = xgb_model
                self.results['XGB'] = self.calculate_metrics(splits['y_test'], y_pred)
                self.predictions['XGB'] = y_pred

                # Gradient Boosting
                print("  c) Gradient Boosting...")
                gb_model = GradientBoostingRegressor(
                    n_estimators=self.config.get('gb_n_estimators', 200),
                    max_depth=self.config.get('gb_max_depth', 6),
                    learning_rate=self.config.get('gb_learning_rate', 0.05),
                    random_state=self.config.get('random_state', 42)
                )
                gb_model.fit(splits['X_ml_train_scaled'], splits['y_train'])
                y_pred = gb_model.predict(splits['X_ml_test_scaled'])
                self.models['GB'] = gb_model
                self.results['GB'] = self.calculate_metrics(splits['y_test'], y_pred)
                self.predictions['GB'] = y_pred

        # Mostrar resultados
        print("\n" + "=" * 80)
        print("RESULTADOS DE MODELOS")
        print("=" * 80)

        for model_name, metrics in self.results.items():
            print(f"\n{model_name}:")
            for metric, value in metrics.items():
                print(f"  {metric}: {value:.3f}")

        return self.models, self.results

    def create_comparison_dataframe(self, splits):
        """Crea DataFrame comparativo de predicciones"""
        df_comparison = pd.DataFrame({
            'y_true': splits['y_test'],
            'X': splits['coords_test'][:, 0] if 'coords_test' in splits else np.nan,
            'Y': splits['coords_test'][:, 1] if 'coords_test' in splits else np.nan
        })

        for model_name, preds in self.predictions.items():
            df_comparison[f'y_pred_{model_name}'] = preds
            df_comparison[f'error_{model_name}'] = preds - splits['y_test']
            df_comparison[f'abs_error_{model_name}'] = np.abs(preds - splits['y_test'])

        return df_comparison

