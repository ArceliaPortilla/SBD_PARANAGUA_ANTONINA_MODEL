    def _analizar_series_temporales_braza(self, df_braza):
      """Analisa séries temporais dos dados Braza com média mensal + banda ±1σ"""
      try:
          import matplotlib.dates as mdates
          from matplotlib import rcParams

          # Mejorar estética global (opcional, pero ayuda mucho)
          rcParams['font.family'] = 'sans-serif'
          rcParams['font.sans-serif'] = ['Arial', 'DejaVu Sans']

          print("\nANÁLISIS DE SERIES TEMPORALES BRAZA:")

          if 'fecha' not in df_braza.columns:
              print("   No hay columna 'fecha' en datos Braza")
              return None

          df_temp = df_braza.copy()
          df_temp['fecha'] = pd.to_datetime(df_temp['fecha'])
          df_temp = df_temp.sort_values('fecha')

          # Variables con nombres en portugués
          variables_info = [
              ('turbidity_NTU', 'Turbidez', 'NTU'),
              ('chla_ugL', 'Clorofila-a', 'µg/L'),
              ('NDCI', 'NDCI', 'NDCI'),
              ('NDTI', 'NDTI', 'NDTI')
          ]

          variables_presentes = [v for v, _, _ in variables_info if v in df_temp.columns]

          if not variables_presentes:
              print("   No se encontraron variables para graficar")
              return None

          n_vars = len(variables_presentes)
          fig, axes = plt.subplots(n_vars, 1, figsize=(14, 4.2 * n_vars), sharex=True)
          if n_vars == 1:
              axes = [axes]

          fig.suptitle('Séries Temporais - Dados de Braza (Qualidade da Água)',
                      fontsize=16, fontweight='bold', y=0.98)

          for idx, var in enumerate(variables_presentes):
              ax = axes[idx]

              nome_var = next(nome for v, nome, _ in variables_info if v == var)
              unidade = next(u for v, _, u in variables_info if v == var)

              # Agrupar por MES (o puedes cambiar a 'Y' para anual)
              df_grouped = df_temp.groupby(df_temp['fecha'].dt.to_period('M'))[var].agg(
                  ['mean', 'std', 'count']
              ).reset_index()

              # Convertir periodo a fecha (primer día del mes)
              df_grouped['fecha'] = df_grouped['fecha'].dt.to_timestamp()
              df_grouped = df_grouped.set_index('fecha').sort_index()

              # Eliminar meses con muy pocos datos (opcional)
              df_grouped = df_grouped[df_grouped['count'] >= 3]

              if df_grouped.empty:
                  ax.text(0.5, 0.5, f"Sin datos suficientes\npara {nome_var}",
                          ha='center', va='center', transform=ax.transAxes, fontsize=12)
                  continue

              # Media
              media = df_grouped['mean']

              # Banda ±1σ
              lower = media - df_grouped['std']
              upper = media + df_grouped['std']

              # Línea de media
              ax.plot(media.index, media,
                      color='#006400',          # verde oscuro
                      linewidth=2.4,
                      label='Média mensal')

              # Banda sombreada
              ax.fill_between(media.index, lower, upper,
                              color='gray', alpha=0.18,
                              label='± 1 desvio padrão')

              # Configuración
              ax.set_ylabel(f'{nome_var} ({unidade})', fontsize=12)
              ax.set_title(f'Série Temporal Média - {nome_var}', fontsize=13, pad=10)
              ax.grid(True, alpha=0.25, linestyle='--')

              # Formato años en X (como en tu ejemplo)
              ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
              ax.xaxis.set_major_locator(mdates.YearLocator())
              plt.setp(ax.get_xticklabels(), rotation=0, ha='center')

              # Leyenda
              ax.legend(loc='upper right', fontsize=10, frameon=True,
                        facecolor='white', edgecolor='lightgray')

          # Etiqueta común para eje X
          fig.text(0.5, 0.04, 'Ano', ha='center', fontsize=13)

          plt.tight_layout(rect=[0, 0.06, 1, 0.96])
          plt.show()

          # Estadísticas (opcional)
          resultados = {'periodo': {...}, 'estadisticas': {}}
          # (puedes mantener o quitar esta parte)

          return resultados

      except Exception as e:
          print(f"   Error: {e}")
          import traceback
          traceback.print_exc()
          return None

