    def plot_cumplimiento_tvu(self, df_eval, model_name='RF', a=0.50, b=0.013, order='Order1a'):
      """
      Gráfico de cumplimiento del TVU (Total Vertical Uncertainty)
      con banda simétrica ± TVU según IHO S-44
      """
      import seaborn as sns
      import numpy as np

      plt.figure(figsize=(11, 7))

      # Scatter de errores absolutos vs profundidad real
      sns.scatterplot(
          data=df_eval,
          x='y_true',
          y=f'abs_error_{model_name}',
          hue=f'cumple_TVU_{model_name}',
          palette={True: 'green', False: 'red'},
          alpha=0.7,
          s=60,
          edgecolor='gray',
          linewidth=0.5
      )

      # Rango de profundidades para la curva
      depths = np.linspace(
          max(0, df_eval['y_true'].min() - 1),
          df_eval['y_true'].max() + 1,
          200
      )

      # Calcular TVU (valor positivo)
      tvu = np.sqrt(a**2 + (b * depths)**2)

      # Banda simétrica: +TVU y -TVU
      plt.plot(depths,  tvu, 'k--', lw=2.2, label=f'+TVU máx (95%) - {order}')
      plt.plot(depths, -tvu, 'k--', lw=2.2, label=f'-TVU máx (95%) - {order}')

      # Rellenar la banda de tolerancia (opcional, pero queda muy visual)
      plt.fill_between(
          depths,
          -tvu,
          tvu,
          color='gray',
          alpha=0.12,
          label='Banda de tolerancia ±TVU'
      )

      # Línea de error cero (referencia)
      plt.axhline(y=0, color='darkgray', linestyle='-', lw=1.2, alpha=0.7)

      # Configuración del gráfico
      plt.title(f'Cumplimiento TVU - {model_name}  |  Ordem {order}\n'
                f'(a = {a:.3f} m   b = {b:.4f})',
                fontsize=14, fontweight='bold', pad=15)

      plt.xlabel('Profundidade real (m)', fontsize=12)
      plt.ylabel('Erro absoluto (m)', fontsize=12)

      plt.legend(loc='upper rigth', fontsize=10, frameon=True, facecolor='white',
                edgecolor='gray', framealpha=0.95)

      plt.grid(True, alpha=0.3, linestyle='--')

      # Ajustar límites para que se vea bien la banda
      plt.ylim(-max(tvu)*1.1, max(tvu)*1.1)

      plt.tight_layout()
      plt.show()

