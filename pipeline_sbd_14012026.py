def delta_idw(lon, lat, p=2):
    dx = lon[:, None] - pontos_delta[:, 0]
    dy = lat[:, None] - pontos_delta[:, 1]
    d = np.sqrt(dx**2 + dy**2)
    d[d < 1e-6] = 1e-6
    w = 1 / (d ** p)
    return np.sum(w * pontos_delta[:, 2], axis=1) / np.sum(w, axis=1)

def horas_desde_epoca(data_hora, epoca=datetime(1992, 1, 1)):
    delta = data_hora - epoca
    return delta.total_seconds() / 3600.0

def preparar_interpoladores(h_tpxo):
    """
    Extrai as coordenadas únicas de longitude e latitude a partir das
    variáveis 2D lon_z e lat_z. Cria interpoladores regulares para cada
    constituinte.
    Retorna:
        lon_1d, lat_1d: arrays 1D com valores únicos de lon e lat
        interp_ha: lista de RegularGridInterpolator para amplitude
        interp_hp: lista de RegularGridInterpolator para fase
        omega_rad: array com velocidades angulares em rad/h
    """
    # Obter arrays 2D de longitude e latitude
    lon_2d = h_tpxo['lon_z'].values  # shape (nx, ny)
    lat_2d = h_tpxo['lat_z'].values  # shape (nx, ny)

    # Extrair valores únicos ordenados (assumindo grade regular)
    # TPXO tem grade regular, então os valores ao longo de cada eixo são constantes
    lon_1d = np.unique(lon_2d)       # deve ser monotônico
    lat_1d = np.unique(lat_2d)       # pode ser decrescente se latitude sul
    # Garantir ordem crescente para o interpolador
    if lat_1d[0] > lat_1d[-1]:
        lat_1d = lat_1d[::-1]
    # Também garantir que lon_1d esteja em [0,360)
    lon_1d = lon_1d % 360
    lon_1d = np.sort(lon_1d)

    # Obter amplitudes e fases
    ha = h_tpxo['ha'].values   # shape (nc, nx, ny)
    hp = h_tpxo['hp'].values   # shape (nc, nx, ny)

    # Reorganizar para (nc, ny, nx) se necessário (o interpolador espera (lat, lon))
    # Como queremos as dimensões (lat, lon), e nossos arrays estão (nx, ny),
    # vamos transpor para (ny, nx) e depois usar (lat_1d, lon_1d).
    ha_reshaped = np.transpose(ha, (0, 2, 1))   # (nc, ny, nx)
    hp_reshaped = np.transpose(hp, (0, 2, 1))

    # Criar interpoladores para cada constituinte
    interp_ha = []
    interp_hp = []
    for k in range(ha_reshaped.shape[0]):
        # Para grade regular, o interpolador espera (lat_1d, lon_1d)
        interp_ha.append(RegularGridInterpolator((lat_1d, lon_1d), ha_reshaped[k],
                                                 bounds_error=False, fill_value=np.nan))
        interp_hp.append(RegularGridInterpolator((lat_1d, lon_1d), hp_reshaped[k],
                                                 bounds_error=False, fill_value=np.nan))

    # Obter velocidades angulares (omega)
    if 'omega' in h_tpxo:
        omega = h_tpxo['omega'].values   # graus/hora
    else:
        # Usar dicionário padrão (velocidades dos principais constituintes)
        const_names = h_tpxo['con'].values.astype(str)
        vel_padrao = {
            'M2': 28.984104, 'S2': 30.0, 'N2': 28.439730, 'K2': 30.082138,
            'K1': 15.041069, 'O1': 13.943035, 'P1': 14.958931, 'Q1': 13.398661,
            'M4': 57.968208, 'MS4': 58.984104, 'MN4': 57.423834, 'M6': 86.952312,
            'S1': 15.0, 'M3': 43.476156, '2N2': 27.895354, 'L2': 29.528479,
            'MU2': 27.968208, 'NU2': 28.512583, 'MK3': 44.025173, 'M8': 115.936416
        }
        omega = np.array([vel_padrao.get(name, 0.0) for name in const_names])

    omega_rad = np.deg2rad(omega)   # rad/h

    return lon_1d, lat_1d, interp_ha, interp_hp, omega_rad

def calcular_mare(lon, lat, horas, lon_1d, lat_1d, interp_ha, interp_hp, omega_rad):
    """
    Calcula a altura da maré η_MSL para cada ponto (lon, lat) no instante `horas`.
    """
    # Normalizar longitude para [0,360)
    lon = np.asarray(lon) % 360
    lat = np.asarray(lat)

    # Pontos para interpolação (lat, lon)
    points = np.column_stack((lat, lon))

    eta = np.zeros(len(lon))
    for k in range(len(interp_ha)):
        H = interp_ha[k](points)
        fase = np.deg2rad(interp_hp[k](points))
        w = omega_rad[k]
        mask = ~np.isnan(H) & (H > 0)   # considera apenas amplitudes válidas
        eta[mask] += H[mask] * np.cos(w * horas - fase[mask])

    return eta

def identificar_colunas(df):
    """
    Identifica as colunas de latitude, longitude, profundidade e data/hora.
    Retorna os nomes originais.
    """
    # Remove espaços extras dos nomes
    df.columns = df.columns.str.strip()

    lat_candidates = ['lat', 'latitude']
    lon_candidates = ['lon', 'long', 'longitude']
    z_candidates   = ['z', 'depth', 'profundidade']
    dt_candidates  = ['datetime', 'date', 'fecha', 'hora']

    col_lat = None
    col_lon = None
    col_z   = None
    col_dt  = None

    for col in df.columns:
        col_low = col.lower()
        if col_low in lat_candidates and col_lat is None:
            col_lat = col
        elif col_low in lon_candidates and col_lon is None:
            col_lon = col
        elif col_low in z_candidates and col_z is None:
            col_z = col
        elif col_low in dt_candidates and col_dt is None:
            col_dt = col

    # Se não encontrou datetime, tenta combinar fecha + hora
    if col_dt is None:
        fecha_col = next((c for c in df.columns if c.lower() == 'fecha'), None)
        hora_col  = next((c for c in df.columns if c.lower() == 'hora'), None)
        if fecha_col is not None and hora_col is not None:
            df['datetime'] = pd.to_datetime(df[fecha_col] + ' ' + df[hora_col].astype(str))
            col_dt = 'datetime'
        else:
            raise ValueError("Coluna de data/hora não encontrada")

    if col_lat is None or col_lon is None or col_z is None:
        raise ValueError("Faltam colunas de lat/lon/z")

    return col_lat, col_lon, col_z, col_dt

def renomear_seguro(df, mapping):
    """
    Renomeia colunas conforme mapping, evitando conflitos.
    Se o novo nome já existir, renomeia a coluna existente para 'nome_orig'.
    """
    for old, new in mapping.items():
        if old == new:
            continue
        if new in df.columns and new != old:
            df.rename(columns={new: f"{new}_orig"}, inplace=True)
        df.rename(columns={old: new}, inplace=True)
    return df

