    def _select_dataset(self, datasets):
        """Selecciona dataset para batimetría"""
        dataset_choice = self.config.get('dataset_choice', 'combined')

        print(f"\nSELECCIÓN DE DATASET PARA BATIMETRÍA:")
        print(f"  Configuración: {dataset_choice}")

        # Mapeo de opciones
        opciones = {
            'combined': ('combinado', datasets.get('combined')),
            'antonina': ('Antonina', datasets.get('antonina')),
            'paranagua': ('Paranaguá', datasets.get('paranagua'))
        }

        if dataset_choice in opciones:
            nombre, dataset = opciones[dataset_choice]
            if dataset is not None and not dataset.empty:
                print(f"   Usando dataset {nombre} ({len(dataset)} registros)")
                return dataset

        # Fallback: usar el primero disponible
        print(f"  Buscando alternativa...")

        for nombre, dataset in [('combinado', datasets.get('combined')),
                               ('Paranaguá', datasets.get('paranagua')),
                               ('Antonina', datasets.get('antonina'))]:
            if dataset is not None and not dataset.empty:
                print(f"  → Usando {nombre} como alternativa ({len(dataset)} registros)")
                return dataset

        print("   No hay datasets disponibles para batimetría")
        return None

    def _es_area_pequena(self, df):
        """Determina si el área de estudio es pequeña"""
        if 'X' not in df.columns or 'Y' not in df.columns:
            return False

        x_min, x_max = df['X'].min(), df['X'].max()
        y_min, y_max = df['Y'].min(), df['Y'].max()

        # Calcular extensión en metros
        x_extent_m = (x_max - x_min) * 111000  # 1 grado ≈ 111 km
        y_extent_m = (y_max - y_min) * 111000

        # Considerar pequeña si menos de 2 km en cualquier dirección
        return x_extent_m < 2000 or y_extent_m < 2000

