class DataPreprocessor:
    """Preprocesamiento avanzado con integración Braza y todos los métodos necesarios"""

    def __init__(self, config):
        self.config = config
        self.scaler = StandardScaler()
        self.feature_columns = None
        self.gmm = None

    def prepare_features(self, df, df_braza=None):
        """
        Prepara características con opción de calibración Braza
        df: datos satelitales (batimetría)
        df_braza: datos de calidad de agua (opcional para calibración)
        """
        print("\n" + "="*80)
        print("PREPROCESAMIENTO DE CARACTERÍSTICAS")
        print("="*80)

        df_processed = df.copy()

        # PASO 1: Calcular logaritmos de bandas
        band_cols = ['B2', 'B3', 'B4', 'B5', 'B8']
        for band in band_cols:
            if band in df_processed.columns:
                df_processed[f'ln_{band}'] = np.log(df_processed[band] + 1e-9)
                print(f"✓ ln_{band} calculado")

        # PASO 2: Calcular índices si faltan
        if 'NDCI' not in df_processed.columns and all(b in df_processed.columns for b in ['B5', 'B4']):
            df_processed['NDCI'] = (df_processed['B5'] - df_processed['B4']) / (df_processed['B5'] + df_processed['B4'])
            print(f"✓ NDCI calculado")

        if 'NDTI' not in df_processed.columns and all(b in df_processed.columns for b in ['B4', 'B3']):
            df_processed['NDTI'] = (df_processed['B4'] - df_processed['B3']) / (df_processed['B4'] + df_processed['B3'])
            print(f"✓ NDTI calculado")

        if 'NDWI' not in df_processed.columns and all(b in df_processed.columns for b in ['B3', 'B5']):
            df_processed['NDWI'] = (df_processed['B3'] - df_processed['B5']) / (df_processed['B3'] + df_processed['B5'])
            print(f"✓ NDWI calculado")

        # PASO 3: Ratio para Stumpf
        if all(b in df_processed.columns for b in ['ln_B2', 'ln_B4']):
            df_processed['lnratio_B2_B4'] = df_processed['ln_B2'] - df_processed['ln_B4']
            print(f"✓ Ratio B2/B4 para Stumpf calculado")

        # PASO 4: CLASIFICACIÓN AGUA CLARA (con o sin calibración Braza)
        print("\n" + "-"*70)
        print("CLASIFICACIÓN DE AGUA CLARA")
        print("-"*70)

        if all(col in df_processed.columns for col in ['NDCI', 'NDTI']):
            if df_braza is not None and not df_braza.empty and self.config.get('use_braza_calibration', True):
                print("Usando calibración con datos Braza...")
                df_processed = self._classify_clear_water_calibrated(df_processed, df_braza)
            else:
                print("Usando clasificación básica (sin calibración)...")
                df_processed = self._classify_clear_water_basic(df_processed)
        else:
            print("No se pueden calcular índices para clasificación de agua")

        # PASO 5: CALIBRACIÓN CON BRAZA (si está disponible)
        if df_braza is not None and not df_braza.empty and self.config.get('use_braza_calibration', True):
            print("\n" + "-"*70)
            print("CALIBRACIÓN CON DATOS BRAZA")
            print("-"*70)
            df_processed = self._apply_braza_calibration(df_processed, df_braza)

        # PASO 6: Definir columnas de características
        self.feature_columns = self._define_feature_columns(df_processed)

        print(f"\n✓ Preprocesamiento completado: {len(df_processed)} registros")
        print(f"  Columnas finales: {len(df_processed.columns)}")

        return df_processed

    def _classify_clear_water_basic(self, df):
        """Clasificación básica de agua clara usando GMM"""
        print("Clasificando agua clara con GMM básico...")

        # Preparar datos para GMM
        X_gmm = df[['NDCI', 'NDTI']].dropna().values

        if len(X_gmm) < 100:
            print(f"  Insuficientes datos para GMM: {len(X_gmm)} muestras")
            df['is_clear_water'] = True  # Marcar todo como agua clara
            return df

        # Submuestreo si es muy grande
        if len(X_gmm) > 10000:
            indices = np.random.choice(len(X_gmm), 10000, replace=False)
            X_gmm_sample = X_gmm[indices]
        else:
            X_gmm_sample = X_gmm

        # Entrenar GMM
        self.gmm = GaussianMixture(n_components=2, random_state=42)
        self.gmm.fit(X_gmm_sample)

        # Predecir en todos los datos
        labels = self.gmm.predict(X_gmm)
        df_gmm = df[['NDCI', 'NDTI']].dropna().copy()
        df_gmm['gmm_label'] = labels

        # Identificar componente de agua clara (menor NDTI)
        comp_stats = []
        for comp in np.unique(labels):
            mask = df_gmm['gmm_label'] == comp
            comp_stats.append({
                'component': comp,
                'mean_NDTI': df_gmm.loc[mask, 'NDTI'].mean(),
                'mean_NDCI': df_gmm.loc[mask, 'NDCI'].mean(),
                'n_samples': mask.sum()
            })

        comp_stats = pd.DataFrame(comp_stats).sort_values('mean_NDTI')
        clear_comp = int(comp_stats.iloc[0]['component'])

        # Asignar etiquetas al DataFrame original
        df_clear = df.copy()
        df_clear['gmm_label'] = np.nan
        df_clear.loc[df[['NDCI', 'NDTI']].dropna().index, 'gmm_label'] = labels
        df_clear['is_clear_water'] = (df_clear['gmm_label'] == clear_comp)

        print(f"  Componente agua clara: {clear_comp}")
        print(f"  Porcentaje agua clara: {df_clear['is_clear_water'].mean()*100:.1f}%")
        print(f"  Muestras agua clara: {df_clear['is_clear_water'].sum()}")

        return df_clear

    def _classify_clear_water_calibrated(self, df_satelital, df_braza):
        """GMM calibrado con datos Braza"""
        print("Usando GMM calibrado con datos Braza...")

        # Preparar datos combinados
        X_satelital = df_satelital[['NDCI', 'NDTI']].dropna().values

        if all(col in df_braza.columns for col in ['NDCI', 'NDTI']):
            X_braza = df_braza[['NDCI', 'NDTI']].dropna().values
        else:
            X_braza = np.array([])

        # Combinar para entrenamiento
        if len(X_braza) > 10:
            X_combined = np.vstack([
                X_satelital[:min(10000, len(X_satelital))],
                X_braza[:min(5000, len(X_braza))]
            ])
            print(f"  Datos entrenamiento: {len(X_combined)} (satelital + Braza)")
        else:
            X_combined = X_satelital[:min(15000, len(X_satelital))]
            print(f"  Datos entrenamiento: {len(X_combined)} (solo satelital)")

        # Entrenar GMM
        self.gmm = GaussianMixture(n_components=2, random_state=42)
        self.gmm.fit(X_combined)

        # Predecir en datos satelitales
        labels = self.gmm.predict(X_satelital)
        df_satelital['gmm_label'] = np.nan
        valid_indices = df_satelital[['NDCI', 'NDTI']].dropna().index
        df_satelital.loc[valid_indices, 'gmm_label'] = labels

        # Identificar componente de agua clara
        df_temp = df_satelital.dropna(subset=['gmm_label'])
        comp_stats = []
        for comp in np.unique(labels):
            mask = df_temp['gmm_label'] == comp
            comp_stats.append({
                'component': comp,
                'mean_NDTI': df_temp.loc[mask, 'NDTI'].mean(),
                'mean_NDCI': df_temp.loc[mask, 'NDCI'].mean(),
                'n_samples': mask.sum()
            })

        comp_stats = pd.DataFrame(comp_stats).sort_values('mean_NDTI')
        clear_comp = int(comp_stats.iloc[0]['component'])

        df_satelital['is_clear_water'] = (df_satelital['gmm_label'] == clear_comp)

        print(f"  Componente agua clara: {clear_comp}")
        print(f"  Porcentaje agua clara: {df_satelital['is_clear_water'].mean()*100:.1f}%")

        return df_satelital

    def _apply_braza_calibration(self, df_satelital, df_braza):
        """Aplica calibración usando datos Braza"""
        if not all(col in df_braza.columns for col in ['NDCI', 'NDTI', 'turbidity_NTU']):
            print("  Datos Braza incompletos para calibración")
            return df_satelital

        # Entrenar modelo de turbidez
        from sklearn.linear_model import LinearRegression

        df_braza_cal = df_braza[['NDCI', 'NDTI', 'turbidity_NTU']].dropna()

        if len(df_braza_cal) < 10:
            print(f"  Muy pocos datos Braza para calibración: {len(df_braza_cal)}")
            return df_satelital

        X_braza = df_braza_cal[['NDTI', 'NDCI']].values
        y_braza = df_braza_cal['turbidity_NTU'].values

        modelo_turbidez = LinearRegression()
        modelo_turbidez.fit(X_braza, y_braza)

        # Predecir turbidez en datos satelitales
        if all(col in df_satelital.columns for col in ['NDTI', 'NDCI']):
            X_sat = df_satelital[['NDTI', 'NDCI']].values
            turbidez_pred = modelo_turbidez.predict(X_sat)
            df_satelital['turbidity_estimated_NTU'] = turbidez_pred

            print(f"  Turbidez estimada: {turbidez_pred.mean():.1f} ± {turbidez_pred.std():.1f} NTU")
            print(f"  R² modelo calibración: {modelo_turbidez.score(X_braza, y_braza):.3f}")

        return df_satelital

    def _define_feature_columns(self, df):
        """Define las columnas de características"""
        feature_sets = {
            'lyzenga': [f'ln_{b}' for b in ['B2', 'B3', 'B4'] if f'ln_{b}' in df.columns],
            'stumpf': ['lnratio_B2_B4'] if 'lnratio_B2_B4' in df.columns else [],
            'ml_basic': ['NDCI', 'NDTI', 'NDWI'] if all(x in df.columns for x in ['NDCI', 'NDTI', 'NDWI']) else [],
            'ml_bands': [f'ln_{b}' for b in ['B2', 'B3', 'B4', 'B5', 'B8'] if f'ln_{b}' in df.columns],
            'coords': ['X', 'Y'] if all(x in df.columns for x in ['X', 'Y']) else []
        }

        # Combinar características para ML
        ml_features = []
        ml_features.extend(feature_sets['ml_bands'])
        ml_features.extend(feature_sets['ml_basic'])
        ml_features.extend(feature_sets['coords'])

        features = {
            'lyzenga': feature_sets['lyzenga'],
            'stumpf': feature_sets['stumpf'],
            'ml': ml_features,
            'coords': feature_sets['coords']
        }

        print("\nConjuntos de características definidos:")
        for key, cols in features.items():
            if cols:
                print(f"  {key}: {len(cols)} características")

        return features

    def split_data(self, df, target_col='Z1'):
        """Divide los datos en train/test"""
        print("\n" + "-"*70)
        print("DIVISIÓN DE DATOS EN TRAIN/TEST")
        print("-"*70)

        # Filtrar solo agua clara si está configurado
        if self.config.get('use_clear_water_only', True) and 'is_clear_water' in df.columns:
            df_model = df[df['is_clear_water']].copy()
            print(f"  Usando solo agua clara: {len(df_model)} muestras ({len(df_model)/len(df)*100:.1f}%)")
        else:
            df_model = df.copy()
            print(f"  Usando todos los datos: {len(df_model)} muestras")

        # Verificar que tenemos características definidas
        if self.feature_columns is None:
            self.feature_columns = self._define_feature_columns(df_model)

        # Preparar características
        X_lyz = df_model[self.feature_columns['lyzenga']].values if self.feature_columns['lyzenga'] else None
        X_stumpf = df_model[self.feature_columns['stumpf']].values if self.feature_columns['stumpf'] else None
        X_ml = df_model[self.feature_columns['ml']].values if self.feature_columns['ml'] else None

        y = df_model[target_col].values

        # Obtener coordenadas si existen
        if all(col in df_model.columns for col in ['X', 'Y']):
            coords = df_model[['X', 'Y']].values
        else:
            coords = None

        # Split indices
        indices = np.arange(len(df_model))
        tr_idx, te_idx = train_test_split(
            indices,
            test_size=self.config.get('test_size', 0.2),
            random_state=self.config.get('random_state', 42),
            shuffle=True
        )

        print(f"  Train: {len(tr_idx)} muestras")
        print(f"  Test: {len(te_idx)} muestras")

        if len(y) > 0:
            print(f"  Profundidad media train: {y[tr_idx].mean():.2f} m")
            print(f"  Profundidad media test: {y[te_idx].mean():.2f} m")

        # Crear diccionario con splits
        splits = {
            'train_indices': tr_idx,
            'test_indices': te_idx,
            'y_train': y[tr_idx],
            'y_test': y[te_idx],
        }

        if coords is not None:
            splits['coords_train'] = coords[tr_idx]
            splits['coords_test'] = coords[te_idx]

        # Dividir características Lyzenga
        if X_lyz is not None and len(X_lyz) > 0:
            splits.update({
                'X_lyz_train': X_lyz[tr_idx],
                'X_lyz_test': X_lyz[te_idx]
            })
            print(f"  Características Lyzenga: {X_lyz.shape[1]}")

        # Dividir características Stumpf
        if X_stumpf is not None and len(X_stumpf) > 0:
            splits.update({
                'X_stumpf_train': X_stumpf[tr_idx],
                'X_stumpf_test': X_stumpf[te_idx]
            })
            print(f"  Características Stumpf: {X_stumpf.shape[1]}")

        # Dividir características ML (con escalado)
        if X_ml is not None and len(X_ml) > 0:
            X_ml_train = X_ml[tr_idx]
            X_ml_test = X_ml[te_idx]

            # Escalar
            X_ml_train_scaled = self.scaler.fit_transform(X_ml_train)
            X_ml_test_scaled = self.scaler.transform(X_ml_test)

