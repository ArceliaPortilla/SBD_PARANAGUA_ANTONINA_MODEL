# FUNÇÃO PARA GRAFICAR ELIPSES GAUSSIANAS DO GMM (VERSÃO FINAL)
# ====================================================

def plot_gaussian_ellipses(gmm, X, labels=None,
                           title="Classificação de Águas - NDCI vs NDTI",
                           save_path=None):
    """
    Gera um gráfico de elipses gaussianas para visualizar os componentes do GMM
    Versão final com cores apropriadas para água clara e turva
    """

    import matplotlib.pyplot as plt
    import matplotlib as mpl
    from scipy import linalg
    import numpy as np
    import itertools
    import pandas as pd

    # Configurar cores específicas para cada tipo
    # Azul claro para água clara, marrom/esverdeado para água turva
    cluster_colors = {
        0: {'points': 'skyblue', 'ellipse': 'blue', 'edge': 'darkblue'},      # Água Clara
        1: {'points': 'sandybrown', 'ellipse': 'brown', 'edge': 'darkgoldenrod'}  # Água Turva
    }

    # Criar figura
    fig, ax = plt.subplots(1, 1, figsize=(10, 8))

    # Obter componentes
    means = gmm.means_
    covariances = gmm.covariances_
    n_components = gmm.n_components

    # Se não há labels, predizer
    if labels is None:
        labels = gmm.predict(X)

    # Calcular estatísticas por componente
    component_stats = []
    for i in range(n_components):
        mask = labels == i
        if np.any(mask):
            component_stats.append({
                'cluster': i,
                'tipo': 'ÁGUA CLARA' if i == 0 else 'ÁGUA TURVA',
                'NDCI_médio': means[i][0],
                'NDTI_médio': means[i][1],
                'n_amostras': np.sum(mask),
                'porcentagem': np.sum(mask) / len(labels) * 100
            })

    # Graficar pontos de dados
    for i in range(n_components):
        mask = labels == i
        if not np.any(mask):
            continue

        mean = means[i]
        covar = covariances[i]

        # Determinar cores baseado no cluster
        colors = cluster_colors.get(i, cluster_colors[0])

        # Nome do cluster
        cluster_name = "ÁGUA CLARA" if i == 0 else "ÁGUA TURVA"

        # Graficar pontos
        ax.scatter(X[mask, 0], X[mask, 1],
                   s=8, c=colors['points'], alpha=0.6,
                   edgecolors=colors['edge'], linewidth=0.3,
                   label=f'Cluster {i} - {cluster_name}')

        # Calcular elipse (2-sigma)
        v, w = linalg.eigh(covar)
        v = 2.0 * np.sqrt(2.0) * np.sqrt(v)

        # Calcular ângulo
        u = w[0] / linalg.norm(w[0])
        angle = np.arctan2(u[1], u[0])
        angle_deg = np.degrees(angle)

        # Criar elipse
        ell = mpl.patches.Ellipse(mean, v[0], v[1],
                                   angle=angle_deg,
                                   color=colors['ellipse'], alpha=0.2,
                                   linewidth=2, fill=True)
        ax.add_patch(ell)

        # Contorno da elipse
        ell2 = mpl.patches.Ellipse(mean, v[0], v[1],
                                    angle=angle_deg,
                                    color=colors['ellipse'], alpha=0.8,
                                    linewidth=2, fill=False)
        ax.add_patch(ell2)

        # Marcar centro
        ax.plot(mean[0], mean[1], 'x', color=colors['ellipse'],
                markersize=12, markeredgewidth=3)

        # Adicionar texto identificando o cluster
        ax.text(mean[0], mean[1], f'  {cluster_name}',
                fontsize=11, fontweight='bold',
                color='black',
                bbox=dict(boxstyle='round,pad=0.3',
                         facecolor='white', alpha=0.8,
                         edgecolor=colors['ellipse']))

    # Configurar gráfico
    ax.set_xlabel('NDCI', fontsize=12, fontweight='bold')
    ax.set_ylabel('NDTI', fontsize=12, fontweight='bold')
    ax.set_title(title, fontsize=14, fontweight='bold', pad=20)
    ax.grid(True, alpha=0.3, linestyle='--')

    # Legenda no canto superior esquerdo (fora do gráfico)
    ax.legend(loc='upper left', bbox_to_anchor=(1.01, 1),
              fontsize=10, frameon=True, fancybox=True, shadow=True)



    # Salvar se especificado
    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"Gráfico salvo em: {save_path}")

    plt.show()

    # Mostrar interpretação
    print("\n" + "="*60)
    print("INTERPRETAÇÃO DOS RESULTADOS")
    print("="*60)
    print(f"✓ Cluster 0 (ÁGUA CLARA):")
    print(f"  • NDCI médio: {means[0][0]:.3f}")
    print(f"  • NDTI médio: {means[0][1]:.3f}")
    print(f"  → Indica águas com menor turbidez")
    print(f"\n✓ Cluster 1 (ÁGUA TURVA):")
    print(f"  • NDCI médio: {means[1][0]:.3f}")
    print(f"  • NDTI médio: {means[1][1]:.3f}")
    print(f"  → Indica águas com maior turbidez")
    print(f"\n✓ Separação clara entre os dois tipos de água")
    print("="*60)

    return fig, ax


