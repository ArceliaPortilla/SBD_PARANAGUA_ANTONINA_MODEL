        import os

        perfiles_dir = os.path.join(output_dir, 'perfiles_batimetricos')
        os.makedirs(perfiles_dir, exist_ok=True)

        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')

        for profile_name, profile_info in profiles.items():
            try:
                # Guardar datos del perfil
                csv_path = os.path.join(perfiles_dir, f'perfil_{profile_name}_{timestamp}.csv')
                profile_info['df'].to_csv(csv_path, index=False)

                # Guardar información del perfil (convertir a tipos serializables)
                info_path = os.path.join(perfiles_dir, f'info_{profile_name}_{timestamp}.json')

                # Convertir a tipos serializables
                info_serializable = {}
                for key, value in profile_info.items():
                    if key == 'df':
                        continue  # No guardar el DataFrame en JSON
                    elif key in ['start_point', 'end_point']:
                        info_serializable[key] = tuple(float(v) for v in value) if value else None
                    elif isinstance(value, (np.float32, np.float64, np.int32, np.int64)):
                        info_serializable[key] = float(value) if isinstance(value, (np.float32, np.float64)) else int(value)
                    elif isinstance(value, np.ndarray):
                        info_serializable[key] = value.tolist()
                    else:
                        info_serializable[key] = value

                import json
                with open(info_path, 'w') as f:
                    json.dump(info_serializable, f, indent=4)

                # Guardar estadísticas
                stats = self.calcular_estadisticas_perfil(profile_info['df'])
                stats_path = os.path.join(perfiles_dir, f'estadisticas_{profile_name}_{timestamp}.json')

                # Convertir estadísticas a tipos serializables
                def convert_stats(obj):
                    if isinstance(obj, dict):
                        return {k: convert_stats(v) for k, v in obj.items()}
                    elif isinstance(obj, (np.float32, np.float64)):
                        return float(obj)
                    elif isinstance(obj, (np.int32, np.int64)):
                        return int(obj)
                    elif isinstance(obj, np.ndarray):
                        return obj.tolist()
                    else:
                        return obj

                stats_serializable = convert_stats(stats)

                with open(stats_path, 'w') as f:
                    json.dump(stats_serializable, f, indent=4)

                print(f" Perfil {profile_name} guardado:")
                print(f"  • Datos: {csv_path}")
                print(f"  • Información: {info_path}")
                print(f"  • Estadísticas: {stats_path}")

            except Exception as e:
                print(f" Error guardando perfil {profile_name}: {e}")

        return perfiles_dir

