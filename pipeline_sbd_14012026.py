        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')

        # Calcular límites del área
        x_min, x_max = df_comparison['X'].min(), df_comparison['X'].max()
        y_min, y_max = df_comparison['Y'].min(), df_comparison['Y'].max()
        x_center, y_center = (x_min + x_max) / 2, (y_min + y_max) / 2

        x_extent_deg = x_max - x_min
        y_extent_deg = y_max - y_min
        x_extent_m = x_extent_deg * 111000
