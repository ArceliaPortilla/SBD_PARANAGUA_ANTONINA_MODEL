class IncertezaVerticalTVU:
    """
    Calcula y evalúa la Incerteza Vertical Total (TVU) según norma IHO S-44
    Permite comparar el error real vs el máximo permitido por orden
    """

    # Tabla de parámetros según edición 6.x de S-44 (valores más usados)
    ORDERS = {
        'Special':   {'a': 0.25,  'b': 0.0075, 'desc': 'Ordem Especial - Áreas críticas'},
        'Order1a':   {'a': 0.50,  'b': 0.013,  'desc': 'Ordem 1a - Navegação crítica'},
        'Order1b':   {'a': 0.50,  'b': 0.013,  'desc': 'Ordem 1b - Navegação costeira'},
        'Order2':    {'a': 1.00,  'b': 0.023,  'desc': 'Ordem 2 - Áreas abertas'}
    }

    def __init__(self, order='Order1a'):
        if order not in self.ORDERS:
            raise ValueError(f"Orden no reconocida. Opciones válidas: {list(self.ORDERS.keys())}")

        self.order = order
        self.a = self.ORDERS[order]['a']
        self.b = self.ORDERS[order]['b']
        self.desc = self.ORDERS[order]['desc']

    def calcular_tvu_max(self, depth):
        """TVU máxima permitida (95% confiança) para una profundidad dada"""
        depth = np.abs(depth)  # Aseguramos profundidad positiva
        return np.sqrt(self.a**2 + (self.b * depth)**2)

    def evaluar_dataframe(self, df,
                         depth_col='y_true',
                         error_cols=None,
                         prefix_error='error_'):
        """
        Evalúa TVU en un DataFrame de comparación

        Parameters:
        -----------
        df : pd.DataFrame
            DataFrame con predicciones y errores (el df_comparison)
        depth_col : str
            Columna con profundidad real (normalmente 'y_true' o 'Z1')
        error_cols : list
            Lista de columnas de error (ej: ['error_RF', 'error_XGB'])
            Si None, busca automáticamente columnas que empiecen con prefix_error
        """
        df_eval = df.copy()

        # Calcular TVU máxima permitida para cada punto
        df_eval['TVU_max'] = df_eval[depth_col].apply(self.calcular_tvu_max)

        # Buscar columnas de error si no se especifican
        if error_cols is None:
            error_cols = [col for col in df_eval.columns if col.startswith(prefix_error)]

        resultados = {}

        print(f"\n{'='*70}")
        print(f"ANÁLISIS DE INCERTEZA VERTICAL (TVU) - {self.order}")
        print(f"{self.desc}")
        print(f"a = {self.a:.3f} m    b = {self.b:.4f}")
        print(f"{'='*70}\n")

        for err_col in error_cols:
            if err_col not in df_eval.columns:
                continue

            model_name = err_col.replace(prefix_error, '')

            # Error absoluto
            df_eval[f'abs_{err_col}'] = np.abs(df_eval[err_col])

            # ¿Cumple TVU? (error absoluto ≤ TVU máxima permitida)
            df_eval[f'cumple_TVU_{model_name}'] = df_eval[f'abs_{err_col}'] <= df_eval['TVU_max']

            # Estadísticas
            n_total = len(df_eval)
            n_valid = df_eval[err_col].notna().sum()
            porc_cumple = df_eval[f'cumple_TVU_{model_name}'].mean() * 100

            resultados[model_name] = {
                'RMSE': np.sqrt((df_eval[err_col]**2).mean()),
                'MAE': df_eval[f'abs_{err_col}'].mean(),
                '% Cumple TVU': porc_cumple,
                'N puntos válidos': n_valid,
                'Cumplimiento global': ' Bueno' if porc_cumple >= 95 else
                                     ' Regular' if porc_cumple >= 80 else ' Insuficiente'
            }

            print(f"Modelo: {model_name}")
            print(f"  • % puntos que cumplen TVU: {porc_cumple:.1f}%")
            print(f"  • Cumplimiento global: {resultados[model_name]['Cumplimiento global']}")
            print(f"  • MAE: {resultados[model_name]['MAE']:.3f} m")
            print(f"  • RMSE: {resultados[model_name]['RMSE']:.3f} m\n")

        # Tabla resumen en bonito
        df_resumen = pd.DataFrame(resultados).T
        print("RESUMEN COMPARATIVO TVU:\n")
        print(df_resumen.round(3))

        return df_eval, df_resumen

