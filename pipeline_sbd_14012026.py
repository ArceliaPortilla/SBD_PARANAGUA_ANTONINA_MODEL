    def calcular_estadisticas_perfil(self, df):
        """Calcula estadísticas detalladas del perfil - CORREGIDA"""
        stats = {}

        if 'z_real' not in df.columns or df['z_real'].isna().all():
            return stats

        # Estadísticas para profundidad real
        stats['real'] = {
            'min': float(df['z_real'].min()),
            'max': float(df['z_real'].max()),
            'mean': float(df['z_real'].mean()),
            'std': float(df['z_real'].std()),
            'range': float(df['z_real'].max() - df['z_real'].min()),
            'valid_points': int(df['z_real'].notna().sum())
        }

        # Estadísticas por modelo
        model_cols = [col for col in df.columns if col.startswith('z_pred_')]

        for col in model_cols:
            model_name = col.replace('z_pred_', '')
            error_col = f'error_{model_name}'
            abs_error_col = f'abs_error_{model_name}'

            if error_col in df.columns and not df[error_col].isna().all():
                errors = df[error_col].dropna()
                if len(errors) > 0:
                    stats[model_name] = {
                        'RMSE': float(np.sqrt(np.nanmean(df[error_col]**2))),
                        'MAE': float(df[abs_error_col].mean()) if abs_error_col in df.columns else np.nan,
                        'Bias': float(df[error_col].mean()),
                        'Std_Error': float(df[error_col].std()),
                        'R2': float(1 - (np.nansum(df[error_col]**2) / np.nansum((df['z_real'] - df['z_real'].mean())**2))) if not np.isnan(df['z_real'].mean()) else np.nan,
                        'Max_Error': float(df[abs_error_col].max()) if abs_error_col in df.columns else np.nan,
                        'Min_Error': float(df[abs_error_col].min()) if abs_error_col in df.columns else np.nan,
                        'Valid_Points': int(errors.count())
                    }

        return stats

