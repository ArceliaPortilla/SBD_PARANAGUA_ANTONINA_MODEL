# Primero, una función auxiliar (puedes ponerla fuera de la clase)
def create_pixel_composite(df, group_cols=['X', 'Y'], value_cols=None):
    """
    Crea composite mediana por píxel (X,Y) de las columnas numéricas relevantes.
    Conserva la fecha más reciente como referencia (opcional).
    """
    if value_cols is None:
        # Columnas típicas a mediar (ajusta según tus datos)
        value_cols = ['B2', 'B3', 'B4', 'B5', 'B8', 'NDCI', 'NDTI', 'NDWI',
                      'ln_B2', 'ln_B3', 'ln_B4', 'ln_B5', 'ln_B8', 'lnratio_B2_B4']

    # Filtrar solo las que existen
    value_cols = [col for col in value_cols if col in df.columns]

    if not value_cols:
        print("No se encontraron columnas numéricas para composite → se usa el df original")
        return df

    print(f"Creando composite mediana por píxel. Columnas: {value_cols}")
    print(f"Registros antes: {len(df)}")

    # Agrupar por coordenadas y calcular mediana
    composite = df.groupby(group_cols)[value_cols].median().reset_index()

    # Opcional: agregar fecha más reciente por píxel (para referencia)
    if 'fecha' in df.columns:
        df['fecha'] = pd.to_datetime(df['fecha'])
        latest_date = df.groupby(group_cols)['fecha'].max().reset_index()
        composite = composite.merge(latest_date, on=group_cols, how='left')

    # Copiar otras columnas no numéricas si existen (e.g. Z1 si es fija por píxel)
    if 'Z1' in df.columns:
        # Asumimos que Z1 es constante por píxel → tomamos el primero
        z1_ref = df.groupby(group_cols)['Z1'].first().reset_index()
        composite = composite.merge(z1_ref, on=group_cols, how='left')

    print(f"Registros después (píxeles únicos): {len(composite)}")
    return composite


