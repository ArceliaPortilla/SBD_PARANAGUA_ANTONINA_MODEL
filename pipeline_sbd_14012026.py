    def limpiar_outliers(self, df, columns=None, factor=1.5):
        """Limpia outliers de las columnas especificadas"""
        if df is None or df.empty:
            return df

        if columns is None:
            # Columnas numéricas por defecto
            numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
            # Excluir coordenadas si están presentes
            columns = [col for col in numeric_cols if col not in ['X', 'Y']]

        df_clean = df.copy()
        outliers_info = {}

        for col in columns:
            if col in df_clean.columns:
                original = df_clean[col].copy()
                df_clean[col] = self.remove_outliers_iqr(df_clean[col], factor=factor)

                # Contar outliers
                n_outliers = (original != df_clean[col]).sum()
                if n_outliers > 0:
                    outliers_info[col] = n_outliers

        if outliers_info:
            print(f"\n Outliers removidos:")
            for col, count in outliers_info.items():
                print(f"  {col}: {count} outliers ({count/len(df)*100:.1f}%)")

        return df_clean

