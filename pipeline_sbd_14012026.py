    def plot_depth_predicted_vs_real_individual(self, df_comparison, model_name, ax=None):
        """
        Gráfico individual de profundidade medida vs real para um modelo específico
        com densidade de probabilidade destacada e colorbar
        """
        import numpy as np
        from scipy import stats
        from scipy.stats import gaussian_kde
        from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

        pred_col = f'y_pred_{model_name}'

        if pred_col not in df_comparison.columns:
            print(f"Modelo {model_name} não encontrado nas colunas")
            return None

        # Filtrar valores não nulos
        mask = ~df_comparison['y_true'].isna() & ~df_comparison[pred_col].isna()
        y_true = df_comparison.loc[mask, 'y_true']
        y_pred = df_comparison.loc[mask, pred_col]

        if len(y_true) < 10:
            print(f"Modelo {model_name} tem poucos dados válidos: {len(y_true)}")
            return None

        # Criar figura/eixo se necessário
        if ax is None:
            fig, ax = plt.subplots(figsize=(9, 7))

        # Cor base do modelo (usado nos pontos de fundo)
        color = self.model_colors.get(model_name, '#ff271c')

        # 1. Scatter de fundo - baixa opacidade para não competir com a densidade
        ax.scatter(y_true, y_pred,
                   color=color,
                   alpha=0.25,           # bem transparente
                   s=12,                 # tamanho moderado
                   edgecolors='none',
                   rasterized=True)      # melhora performance com muitos pontos

        # 2. Densidade de probabilidade (KDE) - pontos mais destacados
        if len(y_true) > 100:
            try:
                xy = np.vstack([y_true, y_pred])
                z = gaussian_kde(xy)(xy)
                idx_sorted = z.argsort()  # densidade alta por cima

                # Scatter da densidade
                sc_density = ax.scatter(y_true.iloc[idx_sorted],
                                       y_pred.iloc[idx_sorted],
                                       c=z[idx_sorted],
                                       s=25,                  # um pouco maiores
                                       alpha=0.85,
                                       cmap='viridis',        # conforme solicitado
                                       edgecolors='none',
                                       rasterized=True)

                # Colorbar com legenda clara
                cbar = plt.colorbar(sc_density, ax=ax, shrink=0.75, pad=0.04)
                cbar.set_label('Densidade de Probabilidade (KDE)',
                              rotation=270,
                              labelpad=18,
                              fontsize=11)
                cbar.ax.tick_params(labelsize=10)

            except Exception as e:
                print(f"Erro ao calcular densidade (KDE): {e}")
                # fallback: scatter normal mais visível
                ax.scatter(y_true, y_pred, color=color, alpha=0.6, s=25)

        # Limites dos eixos (igual ao original)
        all_vals = pd.concat([y_true, y_pred])
        lim_min = all_vals.min() * 0.95 if all_vals.min() > 0 else all_vals.min() * 1.05
        lim_max = all_vals.max() * 1.05
        lim_range = [lim_min, lim_max]

        # Linha 1:1
        ax.plot(lim_range, lim_range, 'k--', linewidth=2, alpha=0.7, label='Linha 1:1')

        # Linha de regressão
        slope, intercept, r_value, _, _ = stats.linregress(y_true, y_pred)
        reg_line = slope * np.array(lim_range) + intercept
        ax.plot(lim_range, reg_line, 'r-', linewidth=2.2, alpha=0.8,
                label=f'Regressão linear (R² = {r_value**2:.3f})')

        # Configuração dos eixos
        ax.set_xlabel('Profundidade Real (m)', fontsize=13)
        ax.set_ylabel('Profundidade Prevista (m)', fontsize=13)
        ax.set_title(f'{model_name} — Profundidade Prevista vs Real',
                    fontsize=15, fontweight='bold', pad=12)

        ax.set_xlim(lim_range)
        ax.set_ylim(lim_range)
        ax.grid(True, alpha=0.35, linestyle='--')
        ax.set_aspect('equal')  # mantém proporção 1:1 visual

        # Legenda
        ax.legend(loc='upper left', fontsize=11, framealpha=0.95)

        # Caixa de estatísticas
        rmse = np.sqrt(mean_squared_error(y_true, y_pred))
        mae = mean_absolute_error(y_true, y_pred)
        r2 = r2_score(y_true, y_pred)
        bias = np.mean(y_pred - y_true)

        stats_text = (f'RMSE: {rmse:.3f} m\n'
                     f'MAE:  {mae:.3f} m\n'
                     f'R²:   {r2:.3f}\n'
                     f'Bias: {bias:.3f} m\n'
                     f'N:    {len(y_true):,}')

        ax.text(0.96, 0.04, stats_text,
                transform=ax.transAxes,
                fontsize=11,
                verticalalignment='bottom',
                horizontalalignment='right',
                bbox=dict(boxstyle='round,pad=0.5',
                         facecolor='white',
                         edgecolor='gray',
                         alpha=0.92))

        if ax is None:
            plt.tight_layout()
            plt.show()

        return ax

