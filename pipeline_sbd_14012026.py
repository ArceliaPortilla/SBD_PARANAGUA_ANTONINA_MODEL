    def _fazer_predicoes(self, df_processado):
        """Faz predições usando os modelos já treinados no pipeline"""
        modelos = self.pipeline.modeler.models  # ← Acesso direto aos modelos treinados!
        if not modelos:
            print("✗ Nenhum modelo encontrado no pipeline treinado")
            return None

        # Pegar as colunas de features já definidas no preprocessor
        feature_columns = self.pipeline.preprocessor.feature_columns

        resultados = {}
        predicoes = {}
        y_true = df_processado['Z1'].values if 'Z1' in df_processado.columns else df_processado['y_true'].values

        for model_name, modelo in modelos.items():
            print(f"  • Predizendo com {model_name}...")

            try:
                if model_name in ['Lyzenga', 'Stumpf']:
                    if model_name == 'Lyzenga' and 'lyzenga' in feature_columns:
                        X = df_processado[feature_columns['lyzenga']].values
                    elif model_name == 'Stumpf' and 'stumpf' in feature_columns:
                        X = df_processado[feature_columns['stumpf']].values
                    else:
                        continue
                else:
                    # Modelos ML usam features escaladas
                    if 'X_ml_train_scaled' in self.pipeline.results.get('splits', {}): # Check against train splits to ensure scaler was fit
                        X = self.pipeline.preprocessor.scaler.transform(
                            df_processado[feature_columns['ml']].values
                        )
                    else:
                        X = df_processado[feature_columns['ml']].values

                y_pred = modelo.predict(X)

                from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

                resultados[model_name] = {
                    'RMSE': np.sqrt(mean_squared_error(y_true, y_pred)),
                    'MAE': mean_absolute_error(y_true, y_pred),
                    'R2': r2_score(y_true, y_pred),
                    'Bias': np.mean(y_pred - y_true),
                    'Std_Error': np.std(y_pred - y_true),
                    'N': len(y_true)
                }

                predicoes[model_name] = y_pred

                print(f"    ✓ R² = {resultados[model_name]['R2']:.3f} | RMSE = {resultados[model_name]['RMSE']:.3f} m")

            except Exception as e:
                print(f"    ✗ Erro em {model_name}: {str(e)[:100]}")

        return {'resultados': resultados, 'predicoes': predicoes, 'y_true': y_true}

